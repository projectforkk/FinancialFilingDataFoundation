from __future__ import annotations

from enum import StrEnum


class P11Reason(StrEnum):
    P11_INVALID_US_IDENTITY = "P11_INVALID_US_IDENTITY"
    P11_TICKER_CIK_AMBIGUOUS = "P11_TICKER_CIK_AMBIGUOUS"
    P11_SEC_RATE_LIMITED = "P11_SEC_RATE_LIMITED"
    P11_SEC_ACCESS_DENIED = "P11_SEC_ACCESS_DENIED"
    P11_SEC_DISCOVERY_FAILED = "P11_SEC_DISCOVERY_FAILED"
    P11_DISCOVERY_FRESHNESS_UNKNOWN = "P11_DISCOVERY_FRESHNESS_UNKNOWN"
    P11_FILING_NOT_FOUND = "P11_FILING_NOT_FOUND"
    P11_FORM_POLICY_MISMATCH = "P11_FORM_POLICY_MISMATCH"
    P11_AMENDED_VARIANT_PRESENT = "P11_AMENDED_VARIANT_PRESENT"
    P11_SLOT_CANDIDATE_CONFLICT = "P11_SLOT_CANDIDATE_CONFLICT"
    P11_TICKER_SNAPSHOT_INVALID = "P11_TICKER_SNAPSHOT_INVALID"
    P11_LOCAL_PACKAGE_CONFLICT = "P11_LOCAL_PACKAGE_CONFLICT"
    P11_ARCHIVE_HOST_REJECTED = "P11_ARCHIVE_HOST_REJECTED"
    P11_CONTENT_TYPE_INVALID = "P11_CONTENT_TYPE_INVALID"
    P11_SIZE_LIMIT_EXCEEDED = "P11_SIZE_LIMIT_EXCEEDED"
    P11_PACKAGE_INVALID = "P11_PACKAGE_INVALID"
    P11_MEMBER_HASH_MISMATCH = "P11_MEMBER_HASH_MISMATCH"
    P11_SOURCE_DRIFT = "P11_SOURCE_DRIFT"
    P11_PRIMARY_DOCUMENT_MISSING = "P11_PRIMARY_DOCUMENT_MISSING"
    P11_HTML_PARSE_FAILED = "P11_HTML_PARSE_FAILED"
    P11_XBRL_INSTANCE_AMBIGUOUS = "P11_XBRL_INSTANCE_AMBIGUOUS"
    P11_XBRL_CONTEXT_UNRESOLVED = "P11_XBRL_CONTEXT_UNRESOLVED"
    P11_XBRL_UNIT_UNRESOLVED = "P11_XBRL_UNIT_UNRESOLVED"
    P11_INLINE_CONTINUATION_INVALID = "P11_INLINE_CONTINUATION_INVALID"
    P11_PROVENANCE_MISMATCH = "P11_PROVENANCE_MISMATCH"
    P11_EVIDENCE_LOCATOR_INVALID = "P11_EVIDENCE_LOCATOR_INVALID"
    P11_STRUCTURED_FACTS_MISSING = "P11_STRUCTURED_FACTS_MISSING"
    P11_SEC_REDIRECT_LIMIT_EXCEEDED = "P11_SEC_REDIRECT_LIMIT_EXCEEDED"
    P11_CONTENT_ENCODING_UNSUPPORTED = "P11_CONTENT_ENCODING_UNSUPPORTED"
    P11_UNSUPPORTED_FPI_PERIODIC_MAPPING = "P11_UNSUPPORTED_FPI_PERIODIC_MAPPING"


class SecError(RuntimeError):
    def __init__(
        self,
        reason_code: P11Reason | str,
        message: str,
        *,
        retryable: bool = False,
    ) -> None:
        super().__init__(message)
        self.reason_code = (
            reason_code.value
            if isinstance(reason_code, P11Reason)
            else str(reason_code)
        )
        self.retryable = retryable
